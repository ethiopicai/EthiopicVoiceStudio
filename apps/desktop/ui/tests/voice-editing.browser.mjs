import test from 'node:test';
import assert from 'node:assert/strict';
import {existsSync,mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createServer} from 'vite';
import {chromium} from 'playwright-core';
const executable=process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
test('voice editing separates text fixes from audio previews, retries and persistent edit controls',{skip:!existsSync(executable),timeout:45000},async()=>{
  const cacheDir=mkdtempSync(join(tmpdir(),'ethiopic-edit-vite-'));
  const server=await createServer({root:fileURLToPath(new URL('..',import.meta.url)),cacheDir,server:{host:'127.0.0.1',port:0,strictPort:false,open:false}});await server.listen();
  const browser=await chromium.launch({executablePath:executable,headless:true});
  try{const page=await browser.newPage({viewport:{width:1500,height:1100}});
    await page.goto(server.resolvedUrls.local[0]+'tests/fixtures/voice-editing.html');
    await page.getByRole('button',{name:'I understand',exact:true}).click();
    await page.getByRole('region',{name:'Editing history',exact:true}).getByRole('button',{name:'Open editing recording: My recording.wav',exact:true}).click();
    await page.getByLabel('Recording transcript',{exact:true}).locator('button').first().waitFor();
    await page.getByRole('button',{name:'Save transcript only',exact:true}).click();
    await page.getByText('Transcript fixed. Audio is unchanged.',{exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>window.editFixture.calls.filter(c=>c.args.action==='preview').length),0);
    await page.getByRole('button',{name:'Change what is said',exact:true}).click();
    await page.getByLabel('New wording',{exact:true}).fill('ሰላም 12 Alex');
    await page.getByRole('region',{name:'Speech text check'}).locator('summary').click();
    await page.getByRole('button',{name:'Use prepared text',exact:true}).click();
    assert.match(await page.getByLabel('New wording',{exact:true}).inputValue(),/አስራ ሁለት Alex/);
    await page.getByLabel('New wording',{exact:true}).fill('ሰላም ወዳጆች');
    await page.locator('ins').getByText('ወዳጆች',{exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Regenerate',exact:true}).isEnabled(),true);
    await page.getByRole('button',{name:'Regenerate',exact:true}).click();
    await page.getByRole('button',{name:'Listen around edit 1',exact:true}).waitFor();
    assert.equal(await page.locator('.waveform-player').count(),2);
    await page.locator('.edit-region').first().waitFor();
    await page.getByRole('button',{name:'Try again',exact:true}).click();
    await page.waitForFunction(()=>window.editFixture.calls.filter(c=>c.args.action==='preview').length===2);
    const seeds=await page.evaluate(()=>window.editFixture.calls.filter(c=>c.args.action==='preview').map(c=>c.args.seed));assert.equal(seeds[1],seeds[0]+1);
    await page.getByRole('button',{name:'Keep this edit',exact:true}).click();
    await page.getByText('Edited regions · Synthetic speech',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Export WAV & edit log',exact:true}).click();
    await page.getByText(/Exported WAV and edit-log.json/).waitFor();
    await page.getByRole('button',{name:'Undo',exact:true}).click();
    await page.getByText('Earlier revision restored.',{exact:true}).waitFor();
    assert.equal(await page.getByText('Edited regions · Synthetic speech',{exact:true}).count(),0);
    await page.evaluate(()=>window.editFixture.unsupported());
    await page.locator('.edit-action-status').getByText('Voice Editing is unavailable on this hardware.',{exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Regenerate',exact:true}).isDisabled(),true);
    const unaligned=await browser.newPage({viewport:{width:1200,height:850}});
    await unaligned.goto(server.resolvedUrls.local[0]+'tests/fixtures/voice-editing.html?unaligned=1');
    await unaligned.getByRole('button',{name:'I understand',exact:true}).click();
    await unaligned.getByRole('button',{name:'Open editing recording: My recording.wav',exact:true}).click();
    await unaligned.getByRole('button',{name:'Change what is said',exact:true}).click();
    await unaligned.locator('.edit-action-status').getByText(/Change a spoken word/).waitFor();
    await unaligned.getByRole('textbox',{name:'New wording',exact:true}).fill('ሰላም ወዳጆች');
    await unaligned.locator('.edit-action-status').getByText(/Align words first/).waitFor();
    assert.equal(await unaligned.getByRole('button',{name:'Regenerate',exact:true}).isDisabled(),true);
    await unaligned.getByRole('button',{name:'Align words',exact:true}).click();
    await unaligned.getByText('Words aligned to this recording.',{exact:true}).waitFor();
    assert.equal(await unaligned.getByRole('textbox',{name:'New wording',exact:true}).inputValue(),'ሰላም ወዳጆች','alignment preserves the proposed speech edit');
    assert.equal(await unaligned.evaluate(()=>window.editFixture.calls.find(call=>call.args.action==='align').args.text),'ሰላም ልጆች','align the original speech, not the proposed replacement');
    await unaligned.evaluate(()=>window.editFixture.failPreview=true);
    await unaligned.getByRole('button',{name:'Regenerate',exact:true}).click();
    const failure=unaligned.getByRole('alert').filter({hasText:'Some words could not be located.'});await failure.waitFor();
    assert.equal(await failure.evaluate(element=>{const box=element.getBoundingClientRect();return box.top>=0&&box.top<innerHeight;}),true,'inference failure stays visible beside the action');
    await unaligned.evaluate(()=>window.editFixture.configure({ready:false,runtimePresent:false}));
    await unaligned.locator('.edit-action-status').getByText(/compatible runtime and models/).waitFor();
    assert.equal(await unaligned.getByRole('button',{name:'Regenerate',exact:true}).isDisabled(),true);
    const numbers=await browser.newPage({viewport:{width:1200,height:950}});
    await numbers.goto(server.resolvedUrls.local[0]+'tests/fixtures/voice-editing.html');
    await numbers.getByRole('button',{name:'I understand',exact:true}).click();await numbers.getByRole('button',{name:'Open editing recording: My recording.wav',exact:true}).click();await numbers.getByRole('button',{name:'Change what is said',exact:true}).click();
    await numbers.getByLabel('New wording',{exact:true}).fill('ዶ/ር አበበ እና ኢ/ር ሀና 12');await numbers.getByRole('button',{name:'Regenerate',exact:true}).click();await numbers.getByRole('button',{name:'Keep this edit',exact:true}).waitFor();
    assert.equal(await numbers.evaluate(()=>window.editFixture.calls.find(call=>call.args.action==='preview').args.text),'ዶክተር አበበ እና ኢንጂነር ሀና አስራ ሁለት','regeneration automatically expands abbreviations and numbers without requiring the apply button');await numbers.close();
    await unaligned.close();
  }finally{await browser.close();await server.close();rmSync(cacheDir,{recursive:true,force:true});}
});
